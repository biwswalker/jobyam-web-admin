export type LocaleKey = keyof typeof locales['th'] | keyof typeof locales['en'];

export function t(key: LocaleKey, lang: 'th' | 'en', vars?: Record<string, string | number>) {
  let str = locales[lang][key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(new RegExp(`{${k}}`, 'g'), String(v));
    });
  }
  return str;
}
